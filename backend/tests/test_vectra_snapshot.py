"""Decoder tests for Vectra v3 snapshots (``structure.vg``).

The fixture is generated by the Go writer (see the plan's Appendix A), never
by our own encoder — otherwise encoder and decoder would mask each other's
bugs.
"""
from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

import pytest

from porto_chatbot.graph.snapshot import SnapshotError, decode_snapshot

_FIX = Path(__file__).parent / "fixtures" / "structure.vg"


def _data():
    return decode_snapshot(_FIX.read_bytes())


def test_decode_returns_all_nodes_and_edges():
    data = _data()
    assert len(data.nodes) == 5
    assert len(data.edges) == 4
    assert data.index_keys == ["beanName", "conditions", "stereotype", "type"]


def test_index_keys_are_returned_as_a_list_in_file_order():
    assert isinstance(_data().index_keys, list)


def test_decode_hydrates_props_and_labels():
    data = _data()
    ctrl = next(n for n in data.nodes if n.key == "bean:orderController")
    assert ctrl.label == "Bean"
    assert ctrl.props["stereotype"] == "RestController"


def test_props_stay_lazy_until_first_access():
    node = next(n for n in _data().nodes if n.key == "bean:orderController")
        # lazy: raw bytes until first access, still exposed as a read-only Mapping
    assert isinstance(node.props, Mapping)
    assert node.props["beanName"] == "orderController"
    assert dict(node.props)["type"] == "com.acme.OrderController"


def test_nil_props_decode_to_an_empty_mapping():
    edge = next(e for e in _data().edges if e.label == "CONTAINS")
    assert (edge.src, edge.dst) == (
        "type:com.acme.OrderService",
        "fn:com.acme.OrderService#pay(int)",
    )
    assert edge.props == {}


def test_edge_props_round_trip():
    edge = next(
        e for e in _data().edges if e.src == "bean:orderService" and e.dst == "bean:payService"
    )
    assert edge.label == "INJECTS"
    assert edge.props["via"] == "lombok-constructor"


def test_decode_rejects_bad_magic():
    with pytest.raises(SnapshotError, match="magic"):
        decode_snapshot(b"XXXX" + b"\x00" * 32)


def test_decode_rejects_bad_crc():
    buf = bytearray(_FIX.read_bytes())
    buf[-1] ^= 0xFF
    with pytest.raises(SnapshotError, match="crc"):
        decode_snapshot(bytes(buf))


def test_decode_rejects_unsupported_version():
    buf = bytearray(_FIX.read_bytes())
    buf[4:6] = (2).to_bytes(2, "little")
    with pytest.raises(SnapshotError, match="version"):
        decode_snapshot(bytes(buf))


def test_decode_rejects_truncated_payload():
    with pytest.raises(SnapshotError, match="truncated"):
        decode_snapshot(_FIX.read_bytes()[:40])


def test_decode_rejects_a_file_cut_mid_string():
    with pytest.raises(SnapshotError, match="truncated"):
        decode_snapshot(_FIX.read_bytes()[:-8])


def test_decode_rejects_forged_counts():
    buf = bytearray(_FIX.read_bytes())
    buf[6:10] = (1 << 30).to_bytes(4, "little")
    with pytest.raises(SnapshotError, match="truncated"):
        decode_snapshot(bytes(buf))
